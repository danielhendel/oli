export function getUserDataDomain(domainId: UserDataDomainId): UserDataDomainDefinition {
  return USER_DATA_DOMAIN_REGISTRY[domainId];
}

export function listUserDataDomains(): readonly UserDataDomainDefinition[] {
  return USER_DATA_DOMAIN_IDS.map((id) => USER_DATA_DOMAIN_REGISTRY[id]);
}

export function isPlaceholderDomain(domainId: UserDataDomainId): boolean {
  return USER_DATA_DOMAIN_REGISTRY[domainId].placeholder;
}
