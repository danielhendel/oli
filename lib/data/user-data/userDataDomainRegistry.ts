export type UserDataDomainId = (typeof USER_DATA_DOMAIN_IDS)[number];

export type UserDataDomainCapabilityLevel =
  | "implemented"
  | "partial"
  | "placeholder"
  | "derived"
  | "control";

export type UserDataDomainDefinition = {
  domainId: UserDataDomainId;
  displayName: string;
  sourceOwners: readonly UserDataSourceId[];
  durableStores: readonly string[];
  currentUiRoutes: readonly string[];
  capabilityLevel: UserDataDomainCapabilityLevel;
  /** Registry-level: whether structured persistence exists for this domain. */
  structuredPersistenceExists: boolean;
  structuredHistoryCapable: boolean;
  baselineCapable: boolean;
  classificationCapable: boolean;
  analyticsCapable: boolean;
  exportCoveredInRegistry: boolean;
  deletionCoveredInRegistry: boolean;
  placeholder: boolean;
  knownGaps: readonly string[];
};

function def(partial: UserDataDomainDefinition): UserDataDomainDefinition {
  return partial;
}

